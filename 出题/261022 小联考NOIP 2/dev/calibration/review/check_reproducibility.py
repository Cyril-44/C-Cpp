#!/usr/bin/env python3
"""Run genall from /tmp with custom directories, sentinels, and exact hash replay."""
import hashlib
import json
import subprocess
import tempfile
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]

def sha(path):
    return hashlib.sha256(path.read_bytes()).hexdigest()

def main():
    report_path = ROOT / 'review/generation.json'
    original_report = report_path.read_bytes()
    original = json.loads(original_report)
    try:
        with tempfile.TemporaryDirectory(prefix='calibration_repro_') as tmp:
            base = Path(tmp)
            data, down = base / 'custom data', base / 'custom down'
            data.mkdir(); down.mkdir()
            for path in [data, down]:
                (path / 'unrelated.txt').write_text('keep me\n')
                (path / 'unrelated.in').write_text('not generated by this script\n')
            subprocess.run(['bash', str(ROOT / 'gen/genall.sh'), str(data), str(down)], cwd='/tmp', check=True)
            checked = 0
            for key, folder in [('cases', data), ('samples', down)]:
                for row in original[key]:
                    for ext, field in [('.in', 'input_sha256'), ('.ans', 'answer_sha256')]:
                        assert sha(folder / (row['id'] + ext)) == row[field]
                        checked += 1
            for path in [data, down]:
                assert (path / 'unrelated.txt').read_text() == 'keep me\n'
                assert (path / 'unrelated.in').read_text() == 'not generated by this script\n'
            report = dict(status='passed', regenerated_pairs=43, matched_files=checked,
                          custom_directories_with_spaces=True, unrelated_files_preserved=4,
                          invocation_cwd='/tmp')
    finally:
        report_path.write_bytes(original_report)
    (ROOT / 'review/reproducibility.json').write_text(json.dumps(report, indent=2) + '\n')
    print(json.dumps(report))

if __name__ == '__main__':
    main()
